        color %= 8;
        double[][] vertex = laevateinnVertex(time);
        for (int[] q : LAEVATEINN_ORDER) {
            t.begin(state).color(RENDER_COLOR_R[color], RENDER_COLOR_G[color], RENDER_COLOR_B[color], alpha);
            quad(t, vertex, q, 1, 1, zPos);
            t.begin(state).color(RENDER_COLOR_R[color], RENDER_COLOR_G[color], RENDER_COLOR_B[color], alpha);
            quad(t, vertex, q, 1, -1, zPos);
        }
