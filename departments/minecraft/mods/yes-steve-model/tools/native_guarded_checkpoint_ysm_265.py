"""Local JSON checkpoints of an already isolated CPU. No pickle or executable deserialization.

Only consume checkpoints generated by this research harness, kept outside Git. A
checkpoint preserves state, not proof that later harness changes are equivalent.
"""
import base64,hashlib,json,zlib,ctypes
import unicorn
from unicorn.unicorn_py3.unicorn import UcContext
from native_unicorn_guarded_ysm_265 import STACK,STACK_SIZE,HEAP,HEAP_SIZE
FIELDS=('level seed stride clock_reads allocations heap_used malloc_calls fopen_calls fgets_calls fclose_calls file_open file_position accelerate_crc modeled_copies opaque_copies heap_writes rollback_count oracle_checks oracle_enabled virtual_loader dladdr_calls loader_ready virtual_platform platform_calls protection_result protection_calls cpuid_calls shadow_events shadow_bytes lazy_new_calls').split()
class ContextHeader(ctypes.Structure):
    # Pinned Unicorn2.1.4 uc_priv.h. Memory snapshot pointers are not CPU state.
    _fields_=[('context_size',ctypes.c_size_t),('mode',ctypes.c_int),('arch',ctypes.c_int),('snapshot_level',ctypes.c_int),('ramblock_freed',ctypes.c_bool),('last_block',ctypes.c_void_p),('fv',ctypes.c_void_p)]
def cpu_only(cpu):cpu.uc.ctl(unicorn.UC_CTL_CONTEXT_MODE,unicorn.UC_CTL_IO_WRITE,ctypes.c_int(unicorn.UC_CTL_CONTEXT_CPU))
def sanitize_context(raw,size,arch,mode):
    n=ctypes.sizeof(ContextHeader);h=ContextHeader.from_buffer_copy(raw[:n])
    if len(raw)!=size or h.context_size+n!=size or h.arch!=arch or h.mode!=mode:raise ValueError('Unrecognized pinned CPU context header')
    start=ContextHeader.snapshot_level.offset
    return raw[:start]+bytes(n-start)+raw[n:]
def pack(data):return base64.b64encode(zlib.compress(bytes(data),9)).decode('ascii')
def unpack(value,size):
    raw=base64.b64decode(value,validate=True);z=zlib.decompressobj();data=z.decompress(raw,size+1)
    if len(data)!=size or z.unconsumed_tail or not z.eof or z.unused_data:raise ValueError('Invalid bounded checkpoint bytes')
    return data
def signatures(cpu):return [(a,b,hashlib.sha256(v).hexdigest()) for a,b,v in cpu.image]
def capture(cpu):
    if cpu.stop is None or not cpu.expected_image_matches():raise ValueError('Checkpoint requires verified stopped state')
    if cpu.reference_digests is not None and cpu.reference_hashes()!=cpu.reference_digests:raise ValueError('Immutable reference changed')
    cpu_only(cpu);ctx=cpu.uc.context_save();raw,size,arch,mode=ctx.__getstate__();raw=sanitize_context(raw,size,arch,mode);patches=[]
    for i,expected in cpu.shadow_expected.items():
        lo,hi,original=cpu.image[i];start=None
        for k,(a,b) in enumerate(zip(original,expected)):
            if a!=b and start is None:start=k
            if a==b and start is not None:patches.append([lo+start,bytes(expected[start:k]).hex()]);start=None
        if start is not None:patches.append([lo+start,bytes(expected[start:]).hex()])
    return {'format':'ysm-guarded-local-checkpoint-v1','engine':unicorn.__version__,'images':signatures(cpu),'context':{'bytes':pack(raw),'size':size,'arch':arch,'mode':mode},'private':{str(a):{'bytes':pack(cpu.uc.mem_read(a,n)),'known':pack(cpu.known[a])} for a,n in ((STACK,STACK_SIZE),(HEAP,HEAP_SIZE))},'opaque':list(cpu.opaque.items()),'fields':{name:getattr(cpu,name) for name in FIELDS},'fixture':cpu.fixture.hex(),'cpuid_leaf1':cpu.cpuid_leaf1,'oracle_seen':sorted(cpu.oracle_seen),'shadow_ranges':cpu.shadow_ranges,'patches':patches,'origin_stop':cpu.stop,'origin_attempted':cpu.attempted,'origin_completed':cpu.completed,'prior_origin_completed':getattr(cpu,'origin_completed',0)}
def restore(cpu,state):
    if state.get('format')!='ysm-guarded-local-checkpoint-v1' or state.get('engine')!=unicorn.__version__:raise ValueError('Checkpoint version mismatch')
    if [tuple(x) for x in state['images']]!=signatures(cpu):raise ValueError('Checkpoint immutable image mismatch')
    if cpu.attempted or cpu.shadow_ranges or cpu.shadow_expected:raise ValueError('Restore requires fresh prepared CPU')
    cpu_only(cpu);probe=cpu.uc.context_save();meta=state['context']
    if (meta['size'],meta['arch'],meta['mode'])!=(probe.size,probe.arch,probe.mode):raise ValueError('Checkpoint CPU layout mismatch')
    raw=sanitize_context(unpack(meta['bytes'],probe.size),probe.size,probe.arch,probe.mode);private={}
    for a,n in ((STACK,STACK_SIZE),(HEAP,HEAP_SIZE)):
        record=state['private'][str(a)];data=unpack(record['bytes'],n);known=unpack(record['known'],n)
        if any(v not in (0,1) for v in known):raise ValueError('Invalid initialized mask')
        private[a]=(data,known)
    fields=dict(state['fields']);fields.setdefault('lazy_new_calls',0)
    if set(fields)!=set(FIELDS) or not 0<=fields['level']<=5 or not 0<=fields['heap_used']<=HEAP_SIZE:raise ValueError('Invalid checkpoint fields')
    if not 0<=fields['shadow_bytes']<=cpu.MAX_IMAGE_BYTES or not 0<=fields['shadow_events']<=cpu.MAX_IMAGE_EVENTS:raise ValueError('Invalid checkpoint quota')
    for a,n in fields['allocations']:
        if not HEAP<=a or not 0<=n<=HEAP_SIZE or a+n>HEAP+HEAP_SIZE:raise ValueError('Invalid checkpoint allocation')
    for a,origin in state['opaque']:
        if cpu.physical(a) is None or cpu.physical(origin) is None:raise ValueError('Invalid opaque address')
    patches=[]
    for address,value in state['patches']:
        data=bytes.fromhex(value);index=cpu.shadow_region(address,len(data))
        if not data or index is None or len(data)>cpu.MAX_IMAGE_BYTES:raise ValueError('Invalid image patch')
        if not all(any(lo<=at<hi and prot&2 for lo,hi,prot in state['shadow_ranges']) for at in range(address,address+len(data))):raise ValueError('Patch lacked writable history')
        patches.append((address,data,index))
    # All byte payloads and CPU layout are validated before restoring the private state.
    for lo,hi,prot in state['shadow_ranges']:cpu.grant_shadow_range(lo,hi-lo,prot)
    for a,(data,known) in private.items():cpu.uc.mem_write(a,data);cpu.known[a]=bytearray(known)
    for name,value in fields.items():setattr(cpu,name,value)
    cpu.opaque=dict(state['opaque']);cpu.fixture=bytes.fromhex(state['fixture']);cpu.cpuid_leaf1=tuple(state['cpuid_leaf1']) if state['cpuid_leaf1'] is not None else None;cpu.oracle_seen=set(state['oracle_seen']);cpu.crc_profile_verified=None
    for address,data,index in patches:
        lo,hi,original=cpu.image[index]
        if index not in cpu.shadow_expected:cpu.shadow_expected[index]=bytearray(original)
        cpu.shadow_expected[index][address-lo:address-lo+len(data)]=data;cpu.uc.mem_write(address,data)
    restored=UcContext.__new__(UcContext);restored.__setstate__((raw,probe.size,probe.arch,probe.mode));cpu.uc.context_restore(restored)
    cpu.stop=None;cpu.pending=None;cpu.journal=[];cpu.writes=[];cpu.attempted=cpu.completed=0;cpu.pc=cpu.reg('RIP');cpu.origin_completed=state['origin_completed']+state.get('prior_origin_completed',0)
    if not cpu.expected_image_matches():raise ValueError('Checkpoint image verification failed')
    cpu.emit('CHECKPOINT_RESUME',f'origin_completed={cpu.origin_completed}',f'pc={cpu.pc:x}','current_run_instruction_counts_reset=true','other_model_counters_inherited=true','host_target_execution=false')
def write_checkpoint(cpu,path):
    state=capture(cpu);payload=json.dumps(state,separators=(',',':')).encode();path.write_bytes(payload);return hashlib.sha256(payload).hexdigest()
def read_checkpoint(cpu,path):
    if path.stat().st_size>48*1024*1024:raise ValueError('Checkpoint too large')
    payload=path.read_bytes();restore(cpu,json.loads(payload));return hashlib.sha256(payload).hexdigest()
